# 1- Atribuição de variável: guarda o valor inteiro 15 na memória

numero = 15

# 2- Condição principal (if): verifica igualdade exata usando '=='

if numero ==  15:

    print("Este numero é o 15")

# 3- Condição secundária (elif): testa se o valor é estritamente menor que 15

elif numero < 15:
        
        print("Este numero é menor que o 15")

# 4- Condição secundária (elif): testa se o valor é estritamente maior que 15

elif numero > 15:
         
         print("Este numero é maior que o 15")